import sys, json
data = json.load(sys.stdin)
print("=== 顶层 keys ===")
print(list(data.keys()))
print()
print("=== anatomy ===")
for k, v in data.get("anatomy", {}).items():
    print(f"  {k}: base64 长度 {len(v)}")
print()
print("=== electrodes ===")
electrodes = data.get("electrodes", [])
print(f"  数量: {len(electrodes)}")
for e in electrodes:
    idx = e.get("idx", "?")
    name = e.get("name", "?")
    entry = e.get("entry_point", "?")
    implant = e.get("implant_endpoint", "?")
    print(f"  #{idx} {name} | entry={entry} | implant={implant}")
    m = e.get("metrics", {})
    cov = m.get("coverage", "?")
    ves = m.get("vessel_margin", "?")
    bra = m.get("brainstem_margin", "?")
    plen = m.get("path_length", "?")
    print(f"    coverage={cov} vessel={ves} brainstem={bra} length={plen}mm")
